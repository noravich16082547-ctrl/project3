-- ---------------------------------------------------------------------------
-- ขั้นที่ 1: ดูก่อนว่าจะโดนลบกี่หอ (ยังไม่ลบจริง)
-- ---------------------------------------------------------------------------
select count(*) as "หอตั้งต้นที่จะลบ"
from dorms
where description like 'หอพักเครือข่ายที่ขึ้นทะเบียนกับสำนักงานบริการที่พักอาศัย%'
   or description like 'หอพักบุคลากร มหาวิทยาลัยราชภัฏเชียงราย%'
   or description like 'หอพักในมหาวิทยาลัยราชภัฏเชียงราย (Uni-dorm)%';

select count(*) as "หอที่จะอยู่ต่อ"
from dorms
where not (description like 'หอพักเครือข่ายที่ขึ้นทะเบียนกับสำนักงานบริการที่พักอาศัย%'
        or description like 'หอพักบุคลากร มหาวิทยาลัยราชภัฏเชียงราย%'
        or description like 'หอพักในมหาวิทยาลัยราชภัฏเชียงราย (Uni-dorm)%')
   or description is null;


-- ---------------------------------------------------------------------------
-- ขั้นที่ 2: ลบข้อมูลที่ผูกกับหอเหล่านั้นก่อน (การจอง / ข้อความ / รีวิว)
--
-- หอตั้งต้นพวกนี้ไม่มีใครจองหรือแชทอยู่แล้ว แต่กันเหนียวไว้
-- เผื่อมีนักศึกษาเผลอกดจองไว้ตอนทดสอบ จะได้ไม่ติด foreign key
-- ---------------------------------------------------------------------------
create temporary table _seed_ids as
select id from dorms
where description like 'หอพักเครือข่ายที่ขึ้นทะเบียนกับสำนักงานบริการที่พักอาศัย%'
   or description like 'หอพักบุคลากร มหาวิทยาลัยราชภัฏเชียงราย%'
   or description like 'หอพักในมหาวิทยาลัยราชภัฏเชียงราย (Uni-dorm)%';

delete from bookings where dorm_id in (select id from _seed_ids);
delete from messages where dorm_id in (select id from _seed_ids);

do $$
begin
  if to_regclass('public.reviews') is not null then
    delete from reviews where dorm_id in (select id from _seed_ids);
  end if;
  if to_regclass('public.dorm_claims') is not null then
    delete from dorm_claims where dorm_id in (select id from _seed_ids);
  end if;
end $$;


-- ---------------------------------------------------------------------------
-- ขั้นที่ 3: ลบตัวหอพักออกจริง
-- ---------------------------------------------------------------------------
delete from dorms where id in (select id from _seed_ids);

drop table _seed_ids;


-- ---------------------------------------------------------------------------
-- ขั้นที่ 4: ตรวจผล — ควรเหลือเฉพาะหอที่เจ้าของหอสร้างเอง
-- ---------------------------------------------------------------------------
select count(*) as "หอที่เหลือทั้งหมด" from dorms;
select name as "ชื่อหอ", hall_type as "ประเภท" from dorms order by name;


