-- ---------------------------------------------------------------------------
-- ส่วนที่ 3: พิกัดหอ ห้ามหลุดออกนอกพื้นที่เชียงราย
--
-- กันเจ้าของหอวางลิงก์ Google Maps ผิดจนหมุดไปตกกลางทะเล
-- แล้วนักศึกษากดนำทางไปผิดที่ (เคยเจอพิมพ์ lat/lng สลับกัน)
-- ถ้าพิกัดหลุดกรอบนี้ ให้เก็บเป็น null ไปเลย ดีกว่าเก็บพิกัดมั่ว
-- ---------------------------------------------------------------------------
create or replace function clamp_dorm_latlng()
returns trigger language plpgsql as $$
begin
  -- กรอบคร่าว ๆ ของจังหวัดเชียงรายและจังหวัดข้างเคียง
  if new.lat is not null and (new.lat < 18.5 or new.lat > 20.5) then
    new.lat := null; new.lng := null;
  end if;
  if new.lng is not null and (new.lng < 99.0 or new.lng > 100.6) then
    new.lat := null; new.lng := null;
  end if;
  return new;
end $$;

drop trigger if exists trg_clamp_dorm_latlng on dorms;
create trigger trg_clamp_dorm_latlng
  before insert or update on dorms
  for each row execute function clamp_dorm_latlng();


